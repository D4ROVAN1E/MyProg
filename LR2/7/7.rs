// Импортируем стандартные модули ввода/вывода
use std::io;

// Определяем функцию count_points, которая принимает строковый срез (&str)
// и возвращает Result. Ok содержит количество стержней (usize),
// а Err содержит строку с описанием ошибки.
fn count_points(rings: &str) -> Result<usize, String> {
    // Строка должна состоять из пар "цвет-позиция", поэтому ее длина должна быть четной.
    if rings.len() % 2 != 0 {
        return Err("Входная строка должна иметь четную длину.".to_string());
    }

    // Создаем вектор для хранения информации о 10 стержнях.
    // Каждый элемент вектора - это массив из 3 булевых значений: [есть_красный, есть_синий, есть_белый].
    // Изначально все значения false, так как на стержнях еще нет колец.
    let mut rods: Vec<[bool; 3]> = vec![[false; 3]; 10];

    // Преобразуем входную строку в вектор символов для удобной итерации по парам.
    let chars: Vec<char> = rings.chars().collect();

    // Итерируемся по вектору символов с шагом 2.
    // Каждый `chunk` будет срезом, содержащим два символа: цвет и позицию.
    for chunk in chars.chunks(2) {
        let color = chunk[0];
        let pos_char = chunk[1];

        // Пытаемся преобразовать символ позиции в цифру (0-9) с помощью `to_digit(10)`.
        let rod_index = match pos_char.to_digit(10) {
            Some(digit) => digit as usize,
            // Если символ не является цифрой 0-9 (None), это недопустимый ввод.
            None => {
                continue; // Пропустить эту пару
            }
        };

        if rod_index >= 10 {
            continue; // Пропустить эту пару
        }

        // Используем `match` для определения цвета кольца и обновления соответствующего
        // флага в массиве для найденного `rod_index`.
        match color {
            'R' => rods[rod_index][0] = true,
            'B' => rods[rod_index][1] = true,
            'W' => rods[rod_index][2] = true,
            _ => {
                continue; // Пропустить эту пару
            }
        }
    }

    // Итерируемся по вектору `rods`, который содержит состояние каждого стержня.
    let count = rods
        .iter() // Создаем итератор по элементам `rods`. Каждый элемент - это `&[bool; 3]`.
        // Фильтруем стержни. Оставляем только те, у которых все три флага (R, B, W) установлены в `true`.
        // `|&&colors|` - это паттерн для разыменования ссылки на массив.
        .filter(|&&colors| colors[0] && colors[1] && colors[2])
        // Считаем количество элементов, оставшихся после фильтрации.
        .count();

    // Возвращаем полученное количество, обернутое в `Ok`, так как все прошло успешно.
    Ok(count)
}

fn main() {
    loop {
        println!("\nВведите строку 'rings' (или 'quit' для выхода):");

        // Создаем пустую строку для хранения ввода пользователя
        let mut input = String::new();

        // Читаем строку из стандартного ввода
        io::stdin()
            .read_line(&mut input)
            .expect("Не удалось прочитать строку");

        // Удаляем пробельные символы в начале/конце строки (включая символ новой строки)
        let input = input.trim();

        // Проверяем, хочет ли пользователь выйти
        if input.eq_ignore_ascii_case("quit") {
            break; 
        }

        // Вызываем нашу функцию count_points с введенной строкой
        match count_points(input) {
            // Если функция вернула Ok(result), выводим результат
            Ok(result) => println!("Результат для '{}': {}", input, result),
            // Если функция вернула Err(e), выводим сообщение об ошибке
            Err(e) => println!("Ошибка для '{}': {}", input, e),
        }
    }
    println!("Программа завершена.");
}